"""The palette where GTK's files do not reach: Flatpak apps and Firefox.

Flatpak apps run in a sandbox that cannot see `~/.config/gtk-3.0`, so the
generated `gtk.css` never reaches them. Firefox does not read GTK's CSS at all.
This module closes both gaps:

    python3 -m vitrail.apps apply <dark|light>

`scripts/apply-settings.sh` reaches it through `vitrail theme apply`, right
after the GTK/Qt colours are written. Nothing here touches the compositor.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Callable

Runner = Callable[[list[str]], str | None]
MARKER = "Generated by Vitrail"
# What a Flatpak app needs to see of the palette: the GTK CSS, fontconfig, the
# Qt colour schemes and the generated icon/cursor themes.
FLATPAK_PATHS = (
    "xdg-config/gtk-3.0",
    "xdg-config/gtk-4.0",
    "xdg-config/fontconfig",
    "xdg-config/qt5ct",
    "xdg-config/qt6ct",
    "xdg-data/icons",
)
FIREFOX_PREF = "toolkit.legacyUserProfileCustomizations.stylesheets"


def log(message: str) -> None:
    print(f"vitrail-apps: {message}", file=sys.stderr, flush=True)


def run_text(argv: list[str]) -> str | None:
    """A command's stdout, or None when it is missing or failed."""
    try:
        found = subprocess.run(argv, capture_output=True, text=True, check=False)
    except OSError:
        return None
    return found.stdout if found.returncode == 0 else None


# --- Flatpak -----------------------------------------------------------------


def override_command() -> list[str]:
    return ["flatpak", "override", "--user"] + [f"--filesystem={path}:ro" for path in FLATPAK_PATHS]


def sync_flatpak(run: Runner = run_text, cache: Path | None = None, force: bool = False) -> bool:
    """Grants every Flatpak app read access to the theme folders, once."""
    command = override_command()
    stamp = (cache / "flatpak-overrides") if cache else None
    key = " ".join(command)
    if not force and stamp is not None and stamp.is_file():
        try:
            if stamp.read_text(encoding="utf-8").strip() == key:
                return False
        except OSError:
            pass
    if not shutil.which("flatpak"):
        log("flatpak is not installed; skipped")
        return False
    if run(command) is None:
        log("flatpak refused the overrides")
        return False
    if stamp is not None:
        try:
            stamp.parent.mkdir(parents=True, exist_ok=True)
            stamp.write_text(key, encoding="utf-8")
        except OSError:
            pass
    return True


# --- Firefox -----------------------------------------------------------------


def _sections(text: str) -> dict[str, dict[str, str]]:
    sections: dict[str, dict[str, str]] = {}
    current: dict[str, str] | None = None
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("[") and line.endswith("]"):
            current = sections.setdefault(line[1:-1], {})
        elif current is not None and "=" in line and not line.startswith(("#", ";")):
            key, _, value = line.partition("=")
            current[key.strip()] = value.strip()
    return sections


def default_profile(mozilla: Path) -> Path | None:
    """The profile Firefox starts with, or None when it never ran."""
    try:
        sections = _sections((mozilla / "profiles.ini").read_text(encoding="utf-8"))
    except OSError:
        return None
    profiles: list[tuple[str, str, bool, bool]] = []
    for name, values in sections.items():
        if not name.startswith("Profile"):
            continue
        path = values.get("Path", "")
        if not path:
            continue
        profiles.append(
            (values.get("Name", ""), path, values.get("IsRelative", "1") == "1", values.get("Default", "0") == "1")
        )
    if not profiles:
        return None
    chosen = next((entry for entry in profiles if entry[3]), None)
    if chosen is None:
        install = next(
            (
                values.get("Default", "")
                for name, values in sections.items()
                if name.startswith("Install") and values.get("Default")
            ),
            "",
        )
        chosen = next((entry for entry in profiles if entry[1] == install), None)
    if chosen is None:
        chosen = next((entry for entry in profiles if entry[0] == "default"), profiles[0])
    name, path, relative, _default = chosen
    return (mozilla / path) if relative else Path(path)


def firefox_css(palette: dict) -> str:
    """The chrome colours, as CSS custom properties and a few safe rules."""

    def role(name: str, fallback: str) -> str:
        return palette.get(name, fallback)

    return f"""/* {MARKER} — do not edit; regenerated with the wallpaper */
:root {{
    --vitrail-surface: {role("surface", "#141218")};
    --vitrail-surface-high: {role("surface_container_high", "#2b292d")};
    --vitrail-on-surface: {role("on_surface", "#e6e0e9")};
    --vitrail-primary: {role("primary", "#a8c7ff")};
    --vitrail-outline: {role("outline", "#938f99")};
}}

#nav-bar, #TabsToolbar, #PersonalToolbar {{
    background-color: var(--vitrail-surface) !important;
    color: var(--vitrail-on-surface) !important;
}}

.tabbrowser-tab[selected] .tab-background {{
    background-color: var(--vitrail-surface-high) !important;
}}

#urlbar-background {{
    background-color: var(--vitrail-surface-high) !important;
    border-color: var(--vitrail-outline) !important;
}}

#urlbar[focused] #urlbar-background {{
    border-color: var(--vitrail-primary) !important;
}}
"""


def write_firefox(profile: Path, palette: dict) -> bool:
    """Enables the chrome stylesheet and writes it, once per palette."""
    if not profile.is_dir():
        return False
    user_js = profile / "user.js"
    text = user_js.read_text(encoding="utf-8") if user_js.exists() else ""
    backup = user_js.with_name(user_js.name + ".before-vitrail")
    if user_js.exists() and not backup.exists():
        backup.write_text(text, encoding="utf-8")
    if FIREFOX_PREF not in text:
        text += "" if text.endswith("\n") or text == "" else "\n"
        text += f'user_pref("{FIREFOX_PREF}", true);\n'
        user_js.write_text(text, encoding="utf-8")
    chrome = profile / "chrome"
    chrome.mkdir(parents=True, exist_ok=True)
    stylesheet = chrome / "userChrome.css"
    stylesheet.write_text(firefox_css(palette), encoding="utf-8")
    return True


# --- entry -------------------------------------------------------------------


def apply(
    mode: str,
    generated: Path,
    cache: Path | None = None,
    run: Runner = run_text,
    mozilla: Path | None = None,
    force: bool = False,
) -> dict:
    """Syncs Flatpak and Firefox with the mode's palette."""
    palette: dict = {}
    try:
        palette = json.loads((generated / f"theme-{mode}.json").read_text(encoding="utf-8")).get("colors", {})
    except (OSError, ValueError):
        log(f"no palette for {mode}")
        return {"flatpak": False, "firefox": ""}
    flatpak = sync_flatpak(run=run, cache=cache, force=force)
    mozilla = mozilla or (Path.home() / ".mozilla" / "firefox")
    profile = default_profile(mozilla)
    firefox = ""
    if profile is None:
        log("no Firefox profile yet: launch Firefox once and re-apply")
    elif write_firefox(profile, palette):
        firefox = str(profile)
    return {"flatpak": flatpak, "firefox": firefox}


def main(argv: list[str] | None = None, run: Runner = run_text, mozilla: Path | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    if args[:1] == ["apply"]:
        mode = args[1] if len(args) > 1 and args[1] in ("dark", "light") else "dark"
        cache = Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache") / "vitrail"
        result = apply(mode, cache / "generated", cache, run=run, mozilla=mozilla)
        print(json.dumps(result, separators=(",", ":")))
        return 0
    print("usage: apps apply <dark|light>", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
