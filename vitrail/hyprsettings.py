"""The settings the compositor starts with, written as a Lua file.

`scripts/apply-settings.sh` pushes the preferences into a running Hyprland with
`hyprctl eval`, and the path unit only fires when a file changes. A fresh login
therefore began with the defaults of `hyprland.lua` (one `us` layout, the
shipped border and opacity) until the next change. This module writes the same
`hl.config` block to `~/.config/hypr/vitrail-settings.lua`, which `hyprland.lua`
loads after its own defaults, so the session starts with the user's values and
the keyboard layouts exist before any input device is created.

    python3 -m vitrail.hyprsettings    rewrites the file from the preferences

Every value is validated before it becomes Lua: a preference file is user
data, not code for the compositor.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

from . import prefs

FILE = "vitrail-settings.lua"
LAYOUTS = "us:"
SWITCH = "grp:alt_shift_toggle"
LAYOUT_MODES = ("dwindle", "scrolling", "master", "monocle")


def lua_string(value: str) -> str:
    """A Lua string literal; quotes, backslashes and control bytes are escaped."""
    out = []
    for char in value:
        if char in '"\\':
            out.append("\\" + char)
        elif ord(char) < 32 or ord(char) == 127:
            out.append(f"\\{ord(char):03d}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def _number(value: str, default: str, low: float, high: float) -> str:
    try:
        number = float(value)
    except ValueError:
        return default
    if not low <= number <= high:
        return default
    return value.strip() if re.fullmatch(r"-?\d+(\.\d+)?", value.strip()) else default


def _integer(value: str, default: int, low: int, high: int) -> int:
    try:
        number = int(float(value))
    except ValueError:
        return default
    return min(max(number, low), high)


def _flag(value: str, default: bool) -> str:
    if value == "true":
        return "true"
    if value == "false":
        return "false"
    return "true" if default else "false"


def keyboard(raw: str) -> tuple[str, str]:
    """ "us:|es:nodeadkeys" becomes layout "us,es" and variant ",nodeadkeys"."""
    layouts, variants = [], []
    for entry in (raw or LAYOUTS).split("|"):
        layout, _, variant = entry.partition(":")
        layouts.append(layout)
        variants.append(variant)
    return ",".join(layouts), ",".join(variants)


def render(values: dict[str, str]) -> str:
    """The Lua file for these preferences."""
    layout, variant = keyboard(values.get("keyboardLayouts") or LAYOUTS)
    switch = values.get("keyboardSwitch") or SWITCH
    window_layout = values.get("windowLayout", "dwindle")
    if window_layout not in LAYOUT_MODES:
        window_layout = "dwindle"
    columns = _integer(values.get("visibleColumns", "2"), 2, 1, 20)
    blur = "true" if values.get("surfaceStyle", "glass") == "glass" else "false"
    follow_mouse = 1 if values.get("focusFollowsMouse", "true") == "true" else 0
    numlock = "false" if values.get("numlockOnStart", "true") == "false" else "true"
    return (
        "-- Generated by Vitrail; `vitrail-apply-settings` rewrites it.\n"
        "hl.config({\n"
        f"    general = {{ border_size = {_integer(values.get('borderWidth', '2'), 2, 0, 20)}, layout = {lua_string(window_layout)} }},\n"
        "    scrolling = {\n"
        f"        column_width = {1.0 / columns:.4f},\n"
        f"        follow_focus = {_flag(values.get('followFocus', 'true'), True)},\n"
        f"        wrap_focus = {_flag(values.get('wrapFocus', 'false'), False)}\n"
        "    },\n"
        "    decoration = {\n"
        f"        rounding = {_integer(values.get('radius', '14'), 14, 0, 100)},\n"
        f"        active_opacity = {_number(values.get('opacityFocused', '0.97'), '0.97', 0, 1)},\n"
        f"        inactive_opacity = {_number(values.get('opacityUnfocused', '0.88'), '0.88', 0, 1)},\n"
        "        blur = {\n"
        f"            enabled = {blur},\n"
        f"            size = {_integer(values.get('blurStrength', '6'), 6, 1, 64)},\n"
        "            passes = 3,\n"
        "            ignore_opacity = false\n"
        "        }\n"
        "    },\n"
        "    input = {\n"
        f"        follow_mouse = {follow_mouse},\n"
        f"        kb_layout = {lua_string(layout)},\n"
        f"        kb_variant = {lua_string(variant)},\n"
        f"        kb_options = {lua_string(switch)},\n"
        f"        numlock_by_default = {numlock}\n"
        "    }\n"
        "})\n"
    )


def target() -> Path:
    base = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    return base / "hypr" / FILE


def write(config: Path | None = None, path: Path | None = None) -> Path:
    """Rewrites the file from the preferences; returns its path."""
    path = path or target()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(prefs.read_prefs(config or prefs.config_dir())), encoding="utf-8")
    return path


def main() -> int:
    print(f"Hyprland startup settings: {write()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
