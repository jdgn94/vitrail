"""Light / dark mode and the wallpaper palette for the rest of the system.

GTK 3/4 get a generated gtk.css and the freedesktop colour-scheme setting,
Qt apps a qt5ct / qt6ct colour scheme, Hyprland its border colour. Files
that belonged to someone else are backed up once before Vitrail takes them.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path
from types import SimpleNamespace
from typing import Callable

from vitrail import colors

MARKER = "Generated by Vitrail"
BACKUP_SUFFIX = ".before-vitrail"
# QPalette::ColorRole order, as qt5ct / qt6ct read it.
QT_ROLES = [
    "WindowText", "Button", "Light", "Midlight", "Dark", "Mid", "Text", "BrightText",
    "ButtonText", "Base", "Window", "Shadow", "Highlight", "HighlightedText", "Link",
    "LinkVisited", "AlternateBase", "NoRole", "ToolTipBase", "ToolTipText",
    "PlaceholderText", "Accent",
]
# Roles that are text: the disabled group fades them.
QT_TEXT_ROLES = {"WindowText", "Text", "ButtonText", "BrightText", "PlaceholderText", "HighlightedText"}
DISABLED_ALPHA = 0.38


def _argb(hex_color: str, alpha: float = 1.0) -> str:
    return f"#{round(alpha * 255):02x}{hex_color.lstrip('#').lower()}"


def qt_scheme(c: dict[str, str]) -> str:
    roles = {
        "WindowText": c["on_surface"], "Button": c["surface_container_high"],
        "Light": c["surface_container_highest"], "Midlight": c["surface_container_high"],
        "Dark": c["surface_container_low"], "Mid": c["surface_container"],
        "Text": c["on_surface"], "BrightText": c["inverse_on_surface"],
        "ButtonText": c["on_surface"], "Base": c["surface_container_low"],
        "Window": c["surface"], "Shadow": c["shadow"], "Highlight": c["primary"],
        "HighlightedText": c["on_primary"], "Link": c["primary"], "LinkVisited": c["tertiary"],
        "AlternateBase": c["surface_container"], "NoRole": c["surface"],
        "ToolTipBase": c["inverse_surface"], "ToolTipText": c["inverse_on_surface"],
        "PlaceholderText": c["on_surface_variant"], "Accent": c["primary"],
    }

    def group(disabled: bool) -> str:
        return ", ".join(
            _argb(roles[role], DISABLED_ALPHA if disabled and role in QT_TEXT_ROLES else 1.0)
            for role in QT_ROLES
        )

    return (f"[ColorScheme]\nactive_colors={group(False)}\n"
            f"disabled_colors={group(True)}\ninactive_colors={group(False)}\n")


def _take(path: Path, text: str) -> None:
    """Writes a file Vitrail owns, keeping a one-time copy of a foreign one."""
    path.parent.mkdir(parents=True, exist_ok=True)
    backup = path.with_name(path.name + BACKUP_SUFFIX)
    if path.exists() and MARKER not in path.read_text(encoding="utf-8", errors="replace") \
            and not backup.exists():
        shutil.copy2(path, backup)
    path.write_text(text, encoding="utf-8")


def set_ini_key(path: Path, section: str, key: str, value: str) -> None:
    """Sets one key, leaving every other line of the file as it was."""
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    if path.exists():
        backup = path.with_name(path.name + BACKUP_SUFFIX)
        if not backup.exists():
            shutil.copy2(path, backup)
    current, done, out = "", False, []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("["):
            if current == section and not done:
                out.append(f"{key}={value}")
                done = True
            current = stripped[1:-1]
        elif current == section and stripped.split("=", 1)[0].strip() == key:
            line, done = f"{key}={value}", True
        out.append(line)
    if not done:
        if current != section:
            out.append(f"[{section}]")
        out.append(f"{key}={value}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def _call(run: Callable[..., object], command: list[str]) -> None:
    try:
        run(command, check=False, capture_output=True)
    except OSError:
        pass


def apply(
    mode: str,
    generated: Path,
    config_home: Path,
    run: Callable[..., object] = subprocess.run,
    hyprland: bool = True,
) -> None:
    palette = json.loads((generated / f"theme-{mode}.json").read_text(encoding="utf-8"))["colors"]
    dark = mode == "dark"

    theme = SimpleNamespace(colors=palette, is_dark=dark)
    css = colors.render_gtk(theme, colors.glass_tokens(theme))
    for version in ("gtk-3.0", "gtk-4.0"):
        _take(config_home / version / "gtk.css", css)
    set_ini_key(config_home / "gtk-3.0" / "settings.ini", "Settings",
                "gtk-application-prefer-dark-theme", "true" if dark else "false")
    _call(run, ["gsettings", "set", "org.gnome.desktop.interface", "color-scheme",
                "prefer-dark" if dark else "prefer-light"])

    scheme = qt_scheme(palette)
    for tool in ("qt5ct", "qt6ct"):
        path = config_home / tool / "colors" / "vitrail.conf"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(scheme, encoding="utf-8")
        conf = config_home / tool / f"{tool}.conf"
        set_ini_key(conf, "Appearance", "color_scheme_path", str(path))
        set_ini_key(conf, "Appearance", "custom_palette", "true")
    # Qt apps read qt6ct only through the platform theme; from the next session.
    env = config_home / "environment.d" / "20-vitrail-qt.conf"
    env.parent.mkdir(parents=True, exist_ok=True)
    env.write_text("QT_QPA_PLATFORMTHEME=qt6ct\n", encoding="utf-8")

    if hyprland and os.environ.get("HYPRLAND_INSTANCE_SIGNATURE") and shutil.which("hyprctl"):
        border = palette["primary"].lstrip("#")
        _call(run, ["hyprctl", "eval",
                    f'hl.config({{ general = {{ col = {{ active_border = "rgba({border}ee)" }} }} }})'])
