"""Swappy, the screenshot annotator, shows its panel and wears the palette.

swappy is GTK 3 and reads `show_panel` from `$XDG_CONFIG_HOME/swappy/config`.
Its look is a generated GTK theme that `@import`s Adwaita's contained sheet and
adds Vitrail's rules on top; swappy is started with `GTK_THEME` naming it, so
no other GTK application is restyled. The theme is rebuilt at every launch from
the current palette and preferences: it can never be stale.
"""

from __future__ import annotations

import os
from pathlib import Path
from types import SimpleNamespace
from typing import Mapping

from . import colors
from .system_theme import DISABLED_ALPHA, set_ini_key
from .style import DEFAULTS, INI_KEYS

THEME = "Vitrail-Swappy"
ADWAITA = "resource:///org/gtk/libgtk/theme/Adwaita/gtk-contained{}.css"
FONT = "Roboto"  # kit/tokens.js font.family
LABEL = 0.85  # kit/tokens.js font.scale.label: captions and the panel's row names
PILL = 999  # a Vitrail button is as round as it is tall (VitrailButton: height / 2)
# The share of the foreground a resting control, a hovered one and a pressed
# one tint the surface with, as the segmented control's track and the ghost
# button's states do.
REST, HOVER, PRESS = 0.08, 0.14, 0.20
# Radius of a field and of a card, as a share of the shell radius.
FIELD = 0.6


def set_panel(show: bool, config_home: Path) -> None:
    """Writes `show_panel` and leaves every other key the user set."""
    set_ini_key(config_home / "swappy" / "config", "Default", "show_panel", "true" if show else "false")


def render_css(
    palette: Mapping[str, str],
    dark: bool,
    radius: int = DEFAULTS["radius"],
    gap: int = DEFAULTS["spacing"],
    font: str = FONT,
    size: int = DEFAULTS["fontBase"],
    glass: bool = True,
) -> str:
    c = palette
    tokens = colors.glass_tokens(SimpleNamespace(colors=c, is_dark=dark))
    if glass:
        base, raised, high = tokens["glass_base"], tokens["glass_raised"], tokens["glass_high"]
    else:
        base, raised, high = c["surface"], c["surface_container"], c["surface_container_high"]
    fg, muted, accent, on_accent = c["on_surface"], c["on_surface_variant"], c["primary"], c["on_primary"]
    border, strong = tokens["border"], tokens["border_strong"]
    rest, hover, press = (colors.rgba(fg, share) for share in (REST, HOVER, PRESS))
    field = round(radius * FIELD)
    small = round(size * LABEL)
    pad, half = gap // 2, gap // 4
    sheet = ADWAITA.format("-dark" if dark else "")
    return f"""/* Generated by Vitrail. Do not edit by hand. */
@import url("{sheet}");

* {{
  font-family: "{font}", sans-serif;
  font-size: {size}px;
  text-shadow: none;
  -gtk-icon-shadow: none;
  outline-color: {accent};
  outline-style: solid;
  outline-width: 0;
  outline-offset: -2px;
}}
*, *:backdrop {{ color: {fg}; }}
*:disabled, *:disabled:backdrop {{ opacity: {DISABLED_ALPHA}; }}

window, window:backdrop, .background {{ background-color: {base}; }}
decoration, decoration:backdrop {{ box-shadow: none; }}

headerbar, headerbar:backdrop {{
  background-image: none;
  background-color: {raised};
  border: none;
  border-bottom: 1px solid {border};
  box-shadow: none;
  min-height: {size * 3}px;
  padding: 0 {gap}px;
}}

paned > box {{
  background-color: {raised};
  border-right: 1px solid {border};
  padding: {gap}px;
}}
paned > box label {{ color: {muted}; font-size: {small}px; }}
separator {{ background-color: {border}; min-width: 1px; min-height: 1px; }}

/* Controls: a tinted pill at rest, brighter under the pointer, the accent when chosen. */
window button, window button:backdrop {{
  background-image: none;
  background-color: {rest};
  border: 1px solid transparent;
  border-radius: {PILL}px;
  box-shadow: none;
  padding: {half + 1}px {gap}px;
  min-height: {size + gap}px;
}}
window button:hover {{ background-color: {hover}; }}
window button:active {{ background-color: {press}; }}
window button:focus {{ outline-width: 2px; }}
window button:checked, window button:checked:hover, window button:checked:backdrop,
window headerbar button.toggle:checked, window headerbar button.toggle:checked:backdrop {{
  background-color: {accent};
  background-image: none;
  border-color: transparent;
}}
window button:checked label, window button:checked image {{ color: {on_accent}; }}

/* The window's actions: ghost buttons, round. */
window headerbar button, window headerbar button:backdrop {{ background-color: transparent; padding: {half + 1}px; }}
window headerbar button:hover {{ background-color: {hover}; }}

/* The tool row, the swatches and the toggles. */
.drawing button {{ padding: {half + 1}px; }}
.color-box button, .color-box button:backdrop {{ background-color: transparent; padding: {half}px {pad}px; }}
.color-box button:hover {{ background-color: {hover}; }}
.color-box button:checked, .color-box button:checked:hover, .color-box button:checked:backdrop {{
  background-color: transparent;
  border-color: {accent};
}}

/* A stepper row: the name, a ghost minus, the value in an outlined field, a ghost plus. */
paned > box > box > button:nth-child(2):nth-last-child(3), paned > box > box > button:nth-child(4) {{
  background-color: transparent;
  padding: {half + 1}px;
}}
paned > box > box > button:nth-child(2):nth-last-child(3):hover, paned > box > box > button:nth-child(4):hover {{
  background-color: {hover};
}}
paned > box > box > button:nth-child(3) {{
  background-color: transparent;
  border: 1px solid {strong};
  border-radius: {field}px;
}}

/* Fields and selections. */
entry, textview text, spinbutton {{
  background-color: transparent;
  background-image: none;
  border: 1px solid {strong};
  border-radius: {field}px;
  box-shadow: none;
  caret-color: {accent};
  padding: {half}px {pad}px;
}}
entry:focus, spinbutton:focus {{ border-color: {accent}; }}
selection, *:selected, *:selected:focus {{ background-color: {accent}; color: {on_accent}; }}

/* Popovers, menus, tooltips, dialogs and the colour chooser. */
popover, popover.background, menu, .menu, .popup {{
  background-color: {high};
  border: 1px solid {border};
  border-radius: {radius}px;
  box-shadow: none;
}}
menuitem, modelbutton {{ border-radius: {field}px; padding: {half}px {pad}px; }}
menuitem:hover, modelbutton:hover {{ background-color: {hover}; }}
tooltip, tooltip.background {{
  background-color: {high};
  border: 1px solid {strong};
  border-radius: {field}px;
  box-shadow: none;
}}
tooltip label {{ font-size: {small}px; }}
dialog, messagedialog, colorchooser {{ background-color: {base}; }}
colorswatch, colorswatch:backdrop {{ border-radius: {field}px; box-shadow: none; border: 1px solid {border}; }}
colorswatch:selected, colorswatch:selected:backdrop {{ border-color: {accent}; }}
colorswatch overlay {{ border-radius: {field}px; }}
window button.suggested-action {{ background-color: {accent}; }}
window button.suggested-action label {{ color: {on_accent}; }}

/* Scrollbars and sliders: bare pills, no trough. */
scrollbar, scrollbar trough, scrollbar:backdrop {{ background: transparent; border: none; }}
scrollbar slider, scrollbar slider:backdrop {{
  background-color: {strong};
  border: 2px solid transparent;
  border-radius: {PILL}px;
  min-width: 6px;
  min-height: 6px;
}}
scrollbar slider:hover {{ background-color: {muted}; }}
scale trough {{ background-color: {rest}; border: none; border-radius: {PILL}px; min-height: 4px; }}
scale highlight {{ background-color: {accent}; border-radius: {PILL}px; }}
scale slider {{ background-color: {accent}; border: none; border-radius: {PILL}px; box-shadow: none; }}
"""


def install_theme(css: str, data_home: Path) -> Path:
    path = data_home / "themes" / THEME / "gtk-3.0" / "gtk.css"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(css, encoding="utf-8")
    return path


def _number(values: Mapping[str, str], name: str) -> int:
    try:
        return int(float(values.get(INI_KEYS[name]) or DEFAULTS[name]))
    except ValueError:
        return int(DEFAULTS[name])


def environment(
    values: Mapping[str, str],
    config_home: Path | None = None,
    data_home: Path | None = None,
    palette: Mapping[str, str] | None = None,
    mode: str | None = None,
    environ: Mapping[str, str] | None = None,
) -> dict[str, str]:
    """Prepares swappy's config and theme; returns the environment to start it in."""
    from . import fonts

    config_home = fonts.config_home() if config_home is None else config_home
    data_home = (
        Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local" / "share") if data_home is None else data_home
    )
    set_panel(str(values.get("annotatePanel", "true")).strip().lower() not in ("false", "0", "no", "off"), config_home)
    env = dict(os.environ if environ is None else environ)
    palette = fonts.active_palette() if palette is None else palette
    if not palette:
        return env
    mode = fonts.active_mode(values.get("appearance", "auto")) if mode is None else mode
    css = render_css(
        palette,
        mode == "dark",
        radius=_number(values, "radius"),
        gap=_number(values, "spacing"),
        font=values.get("fontSystem") or FONT,
        size=_number(values, "fontBase"),
        glass=values.get("surfaceStyle", "glass") != "solid",
    )
    install_theme(css, data_home)
    env["GTK_THEME"] = THEME
    return env
