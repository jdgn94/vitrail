#!/usr/bin/env python3
"""Turns Natural Earth 1:110m land (GeoJSON) into one simplified SVG path.

Usage: python3 -I scripts/world-map.py ne_110m_land.geojson kit/assets/world-110m.svg

The map is equirectangular: x = lon + 180, y = 90 - lat, in tenths of a degree
(viewBox 0 0 3600 1800), so a point is placed with `lon`, `lat` and the width.
Rings are rounded to that grid, repeated points dropped and written as relative
integer steps, which keeps the file small.

Source: Natural Earth, https://www.naturalearthdata.com/ (public domain).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

WIDTH = 3600
HEIGHT = 1800

HEADER = (
    "<!-- Land: Natural Earth 1:110m (ne_110m_land), public domain, "
    "https://www.naturalearthdata.com/. Generated by scripts/world-map.py. -->"
)


def to_grid(lon: float, lat: float) -> tuple[int, int]:
    return round((lon + 180) * 10), round((90 - lat) * 10)


def ring_path(ring: list[list[float]]) -> str:
    points: list[tuple[int, int]] = []
    for lon, lat, *_ in ring:
        point = to_grid(lon, lat)
        if not points or point != points[-1]:
            points.append(point)
    if len(points) > 1 and points[0] == points[-1]:
        points.pop()
    if len(points) < 3:
        return ""
    steps = [f"{b[0] - a[0]} {b[1] - a[1]}" for a, b in zip(points, points[1:])]
    return f"M{points[0][0]} {points[0][1]}l{' '.join(steps)}z"


def polygons(geometry: dict) -> list[list[list[list[float]]]]:
    if geometry["type"] == "Polygon":
        return [geometry["coordinates"]]
    if geometry["type"] == "MultiPolygon":
        return geometry["coordinates"]
    return []


def land_path(collection: dict) -> str:
    rings: list[str] = []
    for feature in collection["features"]:
        for polygon in polygons(feature["geometry"]):
            rings.extend(ring_path(ring) for ring in polygon)
    return "".join(ring for ring in rings if ring)


def svg(collection: dict) -> str:
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f"{HEADER}\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {WIDTH} {HEIGHT}">'
        f'<path fill="#000" fill-rule="evenodd" d="{land_path(collection)}"/></svg>\n'
    )


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    source, target = Path(argv[0]), Path(argv[1])
    collection = json.loads(source.read_text(encoding="utf-8"))
    target.write_text(svg(collection), encoding="utf-8")
    print(f"{target}: {target.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
