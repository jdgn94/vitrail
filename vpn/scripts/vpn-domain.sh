#!/usr/bin/env bash
# /etc/hypraether/vpn/vpn-domain.sh
#
# Applies the tunnel's domain list:
#   1. Regenerates the dnsmasq nftset config (/etc/NetworkManager/dnsmasq.d/
#      vpn-mode.conf) from the user's domain list — dnsmasq keeps resolving
#      the domains dynamically, so entries stay fresh across CDN IP changes.
#   2. Resolves each domain's CURRENT IPs (getent) and inserts them into the
#      active mode's nftables set immediately (vpn_ips / vpn_ips6 in split
#      mode, bypass_ips / bypass_ips6 in full) — the domain takes effect
#      right away, before dnsmasq has ever answered a query for it.
#
# Installed as a real root-owned copy (NOT a symlink): it is the pkexec
# target from the settings UI, and pkexec refuses symlinks / a helper a
# non-root user could rewrite.
#
# Usage:
#   /etc/hypraether/vpn/vpn-domain.sh apply
set -euo pipefail

CMD="${1:?usage: vpn-domain.sh apply}"
[[ "$CMD" == "apply" ]] || {
    echo "vpn-domain: unknown command \"$CMD\"" >&2
    exit 1
}

die() {
    printf '\033[31m[ERROR]\033[0m %s\n' "$*" >&2
    exit 1
}
info() { printf '\033[32m[INFO]\033[0m  %s\n' "$*"; }
log() { echo "vpn-domain: $*" >&2; }

[[ $EUID -ne 0 ]] && die "Run as root: sudo $0 apply"

ENV_FILE="/etc/hypraether/vpn/env"
if [[ -f "$ENV_FILE" ]]; then
    # shellcheck disable=SC1091
    source "$ENV_FILE"
fi

MODE="${VPN_MODE:-split}"
USER_VPN_DIR="$(dirname "${VPN_VAULT:-}")"
DOMAINS_FILE="$USER_VPN_DIR/domains"
DMASQ_CONF="/etc/NetworkManager/dnsmasq.d/vpn-mode.conf"

[[ -n "$USER_VPN_DIR" ]] || die "VPN_VAULT not set (is /etc/hypraether/vpn/env installed?)"
[[ -n "${VPN_USER:-}" ]] || die "VPN_USER not set (re-run vpn/install.sh)"

if [[ "$MODE" == "full" ]]; then
    IP_SET="bypass_ips"
    IP6_SET="bypass_ips6"
else
    IP_SET="vpn_ips"
    IP6_SET="vpn_ips6"
fi

# Read as the user (this runs passwordless through pkexec, and the path is in
# their tree) and only hostnames kept: the list ends up in a world-readable
# dnsmasq config, so a symlinked secret must never reach it.
read_domains() {
    setpriv --reuid="$VPN_USER" --regid="$(id -g "$VPN_USER")" --init-groups -- \
        cat -- "$DOMAINS_FILE" 2>/dev/null \
        | grep -E '^[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$' \
        | head -n 1000 || true
}

# resolve_ips <family> <domain> -> unique IPs, one per line.
resolve_ips() {
    local family="$1" domain="$2"
    if [[ "$family" == "ip" ]]; then
        getent ahostsv4 "$domain" 2>/dev/null | awk '{print $1}' | sort -u
    else
        getent ahostsv6 "$domain" 2>/dev/null | awk '{print $1}' | sort -u
    fi
}

regenerate_dnsmasq() {
    install -d -m 755 /etc/NetworkManager/dnsmasq.d
    local domains nftset4 nftset6
    domains="$(read_domains | paste -sd/ -)"
    if [[ -n "$domains" ]]; then
        nftset4="nftset=/$domains/4#ip#vpn_split#$IP_SET"
        nftset6="nftset=/$domains/6#ip6#vpn_split#$IP6_SET"
    else
        nftset4="nftset=/4#ip#vpn_split#$IP_SET"
        nftset6="nftset=/6#ip6#vpn_split#$IP6_SET"
    fi
    {
        printf '# Generated by vpn-domain.sh — do not edit by hand.\n'
        printf '# Add/remove domains via the settings UI or: hypraether-vpn domain add <name>\n'
        printf '# List source: %s\n' "$DOMAINS_FILE"
        printf '\n'
        printf '%s\n' "$nftset4"
        printf '%s\n' "$nftset6"
        printf '\nserver=8.8.8.8\nserver=1.1.1.1\nserver=8.8.4.4\n'
    } >"$DMASQ_CONF"
}

# insert_ips <family> <set> <domain> — idempotent (`nft add element` on an
# interval set merges existing addresses, verified live). A real failure is
# non-fatal: dnsmasq repopulates the sets on the next DNS query anyway.
insert_ips() {
    local family="$1" set="$2" domain="$3" ips elements=""
    ips="$(resolve_ips "$family" "$domain")"
    [[ -n "$ips" ]] || return 0
    while IFS= read -r ip; do
        [[ -n "$ip" ]] || continue
        elements="${elements:+$elements, }$ip"
    done <<<"$ips"
    if ! nft add element "$family" vpn_split "$set" "{ $elements }" 2>/dev/null; then
        log "nft add element failed for $domain (set $set) — dnsmasq will populate it dynamically."
    fi
}

apply() {
    regenerate_dnsmasq
    systemctl restart NetworkManager
    info "Regenerated $DMASQ_CONF ($MODE) and restarted NetworkManager."

    local domain
    while IFS= read -r domain; do
        [[ -n "$domain" ]] || continue
        insert_ips ip "$IP_SET" "$domain"
        insert_ips ip6 "$IP6_SET" "$domain"
    done < <(read_domains)
    info "Inserted current IPs for all domains into $IP_SET / $IP6_SET."
}

apply
